"""Tests for Tools/gen_no_disenchant.py (#6), on tiny fixture tables.

Run by tests/run.ps1 and CI: python tests/test_gen_no_disenchant.py
"""

import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.join(HERE, "..", "Tools"))
import gen_no_disenchant as gen  # noqa: E402

SPARSE = """ID,OverallQualityID,Flags_0,InventoryType
1,2,32768,13
2,2,0,13
3,1,32768,13
4,5,32768,13
5,3,32769,2
6,4,32768,5
7,2,32768,0
8,2,32768,13
9,3,32768,17
"""
# ID 8 is armor-classed but missing from Item: skipped. 7 has no slot.
ITEM = """ID,ClassID,SubclassID,InventoryType
1,2,7,13
2,2,7,13
3,2,7,13
4,2,7,13
5,4,0,2
6,4,4,5
7,4,0,0
9,0,0,17
"""

failures = 0


def check(cond, label):
    global failures
    if cond:
        print("  ok: " + label)
    else:
        failures += 1
        print("  FAIL: " + label)


def write(folder, name, text):
    path = os.path.join(folder, name)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    return path


with tempfile.TemporaryDirectory() as tmp:
    sparse = write(tmp, "forever-itemsparse-1.2.3.4.csv", SPARSE)
    item = write(tmp, "forever-item-1.2.3.4.csv", ITEM)
    ids = gen.flagged_ids(gen.read(sparse), gen.read(item))
    check(ids == [1, 5, 6], "flagged weapons/armor of quality 2-4 in a slot: %r" % ids)
    check(2 not in ids, "no flag: not listed")
    check(3 not in ids and 4 not in ids, "white and legendary: not listed")
    check(5 in ids, "the bit is tested, not the whole value (32769)")
    check(7 not in ids, "no equip slot: not listed")
    check(8 not in ids, "missing from Item: skipped")
    check(9 not in ids, "not a weapon or armor: not listed")

    out = os.path.join(tmp, "NoDisenchant.lua")
    code = gen.main(["--sparse", sparse, "--item", item, "--out", out])
    text = open(out, encoding="utf-8").read()
    check(code == 0, "generates")
    check('build = "1.2.3.4", count = 3' in text, "the header data names the build and the count")
    check("    1, 5, 6," in text, "the ids")

    other = write(tmp, "forever-item-1.2.3.5.csv", ITEM)
    code = gen.main(["--sparse", sparse, "--item", other, "--out", out])
    check(code == 2, "different builds are refused")

    try:
        gen.build_of(os.path.join(tmp, "items.csv"))
        check(False, "a file name without a build is refused")
    except ValueError:
        check(True, "a file name without a build is refused")

# The shipped file is what the generator writes from its recorded build.
shipped = open(os.path.join(HERE, "..", "Data", "NoDisenchant.lua"), encoding="utf-8").read()
check("GENERATED by Tools/gen_no_disenchant.py" in shipped, "Data/NoDisenchant.lua is the generator's")
db = os.path.join(HERE, "..", "..", "References", "Forever", "db")
build = shipped.split('build = "')[1].split('"')[0]
s, i = (os.path.join(db, "forever-%s-%s.csv" % (t, build)) for t in ("itemsparse", "item"))
if os.path.exists(s) and os.path.exists(i):
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "NoDisenchant.lua")
        gen.main(["--sparse", s, "--item", i, "--out", out])
        check(open(out, encoding="utf-8").read() == shipped.replace("\r\n", "\n"),
              "regenerating from build %s gives the shipped file" % build)
else:
    print("  skip: the build %s tables aren't in References/Forever/db here" % build)

print("test_gen_no_disenchant: %s" % ("%d FAILED" % failures if failures else "passed"))
sys.exit(1 if failures else 0)
