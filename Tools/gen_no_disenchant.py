"""Generate Data/NoDisenchant.lua from the client's own item tables (#6).

The list is every weapon or armor piece in an equip slot, of quality 2-4
(uncommon to epic), that the client flags as never disenchantable:
ItemSparse Flags_0 bit 0x8000 (ITEM_FLAG_NO_DISENCHANT). Item.ClassID and
Item.InventoryType say what the item is; ItemSparse says its quality and flags.

The inputs are the wago.tools exports kept in References/Forever/db (the shared
wago-tools skill saves them). Both must be from the same build:

    python Tools/gen_no_disenchant.py \
        --sparse ../References/Forever/db/forever-itemsparse-1.60.1.70532.csv \
        --item   ../References/Forever/db/forever-item-1.60.1.70532.csv

Standard library only. tests/test_gen_no_disenchant.py covers it.
"""

import argparse
import csv
import os
import re
import sys

NO_DISENCHANT = 0x8000
CLASSES = (2, 4)            # weapon, armor
QUALITIES = (2, 3, 4)       # uncommon, rare, epic: what ItemDisenchantLoot covers
PER_LINE = 10

BUILD_RE = re.compile(r"-(\d+\.\d+\.\d+\.\d+)\.csv$")


def build_of(path):
    m = BUILD_RE.search(os.path.basename(path))
    if not m:
        raise ValueError("no build in the file name: " + path)
    return m.group(1)


def read(path):
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def flagged_ids(sparse_rows, item_rows):
    """Sorted ids of the flagged equipment. Rows missing from Item are skipped."""
    items = {row["ID"]: row for row in item_rows}
    ids = []
    for row in sparse_rows:
        item = items.get(row["ID"])
        if not item:
            continue
        if int(row["OverallQualityID"]) not in QUALITIES:
            continue
        if int(item["ClassID"]) not in CLASSES or int(item["InventoryType"]) <= 0:
            continue
        if int(row["Flags_0"]) & NO_DISENCHANT:
            ids.append(int(row["ID"]))
    return sorted(ids)


def render(ids, build):
    lines = [
        "local _, Shatter = ...",
        "",
        "-- GENERATED by Tools/gen_no_disenchant.py: don't edit by hand (#6).",
        "--",
        "-- Weapons and armor in an equip slot, uncommon to epic, that the client",
        "-- flags as never disenchantable (ItemSparse Flags_0 & 0x8000,",
        "-- ITEM_FLAG_NO_DISENCHANT): enchanter-made wands, PvP insignias and rank",
        "-- gear, some quest items. From the client's ItemSparse and Item tables,",
        "-- build %s (wago.tools exports, References/Forever/db)." % build,
        "-- ItemScanner:CanBeDisenchanted reads it; Constants.USE_NO_DISENCHANT_LIST",
        "-- turns it off.",
        "",
        "local ids = {",
    ]
    for i in range(0, len(ids), PER_LINE):
        lines.append("    " + ", ".join(str(n) for n in ids[i:i + PER_LINE]) + ",")
    lines += [
        "}",
        "",
        "local set = {}",
        "for _, id in ipairs(ids) do set[id] = true end",
        "",
        "Shatter.NoDisenchant = { build = %s, count = %d, ids = set }" % ('"' + build + '"', len(ids)),
        "",
    ]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--sparse", required=True, help="forever-itemsparse-<build>.csv")
    parser.add_argument("--item", required=True, help="forever-item-<build>.csv")
    parser.add_argument("--out", default=os.path.join("Data", "NoDisenchant.lua"))
    args = parser.parse_args(argv)

    sparse_build, item_build = build_of(args.sparse), build_of(args.item)
    if sparse_build != item_build:
        print("refused: ItemSparse is build %s but Item is build %s" % (sparse_build, item_build),
              file=sys.stderr)
        return 2
    ids = flagged_ids(read(args.sparse), read(args.item))
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(ids, sparse_build))
    print("%d items, build %s -> %s" % (len(ids), sparse_build, args.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
